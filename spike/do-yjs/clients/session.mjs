import * as Y from 'yjs';
import WebSocket from 'ws';
import YProvider from 'y-partyserver/provider';
const host = 'localhost:8787', room = 'sess-' + Date.now();
const mk = () => { const doc = new Y.Doc(); const p = new YProvider(host, room, doc, { connect: true, WebSocketPolyfill: WebSocket, party: 'doc-room', protocol: 'ws' }); return { doc, p }; };
const cs = [mk(), mk()];
await Promise.all(cs.map((c) => new Promise((r) => (c.p.synced ? r() : c.p.on('synced', (s) => s && r())))));
const base = (await (await fetch(`http://${host}/parties/doc-room/${room}/stats`)).json()).inbound;
const rnd = () => 'abcde'.slice(0, 1 + Math.floor(Math.random() * 5));
const t = cs.map((c) => setInterval(() => { const x = c.doc.getText('source'); x.insert(x.length, rnd()); }, 1000 / 3));
await new Promise((r) => setTimeout(r, 60000));
t.forEach(clearInterval);
await new Promise((r) => setTimeout(r, 2000));
const end = (await (await fetch(`http://${host}/parties/doc-room/${room}/stats`)).json()).inbound;
console.log(`base=${base} end=${end} inbound=${end - base} total=${end}`);
cs.forEach((c) => c.p.destroy()); process.exit(0);
